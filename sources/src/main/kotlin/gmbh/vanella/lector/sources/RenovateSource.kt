package gmbh.vanella.lector.sources

import gmbh.vanella.lector.core.BranchPolicy
import gmbh.vanella.lector.core.PackageUpdate
import gmbh.vanella.lector.core.PullRequest
import gmbh.vanella.lector.core.SourceUpdate
import gmbh.vanella.lector.core.UpdateSource
import org.slf4j.LoggerFactory

private val logger = LoggerFactory.getLogger(RenovateSource::class.java)

private const val BRANCH_PREFIX = "renovate/"
private const val TABLE_INTRO = "This PR contains the following updates:"
private const val RELEASE_NOTES = "### Release Notes"

// What follows the release notes in Renovate's body.
private val RELEASE_NOTES_END = listOf("\n### Configuration", "\n - [ ] <!-- rebase-check -->", "\nThis PR was generated by")

// Renovate datasources (the package registries in its merge-confidence badges) and the ecosystem each one is.
private val ECOSYSTEMS =
    mapOf(
        "maven" to "maven",
        "npm" to "npm",
        "pypi" to "pypi",
    )

// Update types that change a digest, a range, or lock files, but no version.
private val NO_VERSION_CHANGE = setOf("digest", "pindigest", "pin", "lockfilemaintenance")

// `1.0` → `2.0`, also inside a diff link, and with the ASCII arrow of older Renovate versions.
private val CHANGE = Regex("""`([^`]*)` (?:→|->) `([^`]*)`""")
private val LINK_TEXT = Regex("""^\[([^\]]+)]""")
private val BADGE_DATASOURCE = Regex("""/badges/[a-z]+/([a-z0-9-]+)/""")

// A short or full commit hash: what a digest update shows when the table has no update column.
private val DIGEST = Regex("""[0-9a-f]{7}|[0-9a-f]{40}""")

// Renovate breaks GitHub's autolinks (`#123`, `@name`) with a zero-width space.
private const val ZERO_WIDTH_SPACE = "&#8203;"

/**
 * Renovate's PRs (concept section 3): recognized by the `renovate/` branch, read from the update table and the release
 * notes in the PR body. Every row of a grouped PR is a change. Needs no configuration in Renovate.
 */
class RenovateSource : UpdateSource {
    override fun recognizes(pr: PullRequest) = pr.headBranch.startsWith(BRANCH_PREFIX)

    override fun read(pr: PullRequest) = SourceUpdate(updates(pr.body), releaseNotes(pr.body), BranchPolicy.IN_PLACE)

    private fun updates(body: String): List<PackageUpdate> {
        val lines = body.lines()
        val intro = lines.indexOfFirst { it.trim() == TABLE_INTRO }
        val table =
            lines
                .drop(intro + 1)
                .dropWhile { it.isBlank() }
                .takeWhile { it.startsWith("|") }
        if (intro < 0 || table.size < 2) return emptyList()
        val header = cells(table.first()).map { it.lowercase() }
        return table.drop(2).mapNotNull { row -> update(header, cells(row)) }
    }

    private fun update(
        header: List<String>,
        row: List<String>,
    ): PackageUpdate? {
        val cell = { name: String -> header.indexOf(name).let { row.getOrNull(it) } }
        val name = cell("package")
        val change = cell("change")?.let { CHANGE.find(it) }
        if (name == null || change == null) return null
        val (from, to) = change.destructured
        if (!changesVersion(cell("update"), from, to)) return null
        val packageName = packageName(name)
        val badge = row.firstNotNullOfOrNull { BADGE_DATASOURCE.find(it) }
        val datasource = if (badge == null) null else badge.groupValues[1]
        val ecosystem = datasource?.let(ECOSYSTEMS::get)
        val known = datasource == null || ecosystem != null
        if (!known) logger.info("Skipping {}: no ecosystem for Renovate's {} datasource", packageName, datasource)
        return if (known) PackageUpdate(ecosystem, packageName, from, to) else null
    }

    /** Whether a row moves a version, not a digest, a range, or lock files. Without an update column, a digest shows as hashes. */
    private fun changesVersion(
        updateType: String?,
        from: String,
        to: String,
    ): Boolean {
        val digests = DIGEST.matches(from) && DIGEST.matches(to)
        return updateType?.lowercase() !in NO_VERSION_CHANGE && !digests
    }

    /** The link text, or the text before Renovate's `([source](…))` and `([changelog](…))` links. */
    private fun packageName(cell: String): String {
        val link = LINK_TEXT.find(cell)
        val name = if (link == null) cell.substringBefore(" (") else link.groupValues[1]
        return name.replace(ZERO_WIDTH_SPACE, "").trim()
    }

    private fun cells(row: String) =
        row
            .trim()
            .removePrefix("|")
            .removeSuffix("|")
            .split("|")
            .map { it.trim() }

    private fun releaseNotes(body: String): String? {
        val start = body.indexOf(RELEASE_NOTES)
        if (start < 0) return null
        val notes = body.substring(start + RELEASE_NOTES.length)
        val end = RELEASE_NOTES_END.map { notes.indexOf(it) }.filter { it >= 0 }.minOrNull() ?: notes.length
        return notes
            .take(end)
            .trim()
            .removeSuffix("---")
            .trim()
            .replace(ZERO_WIDTH_SPACE, "")
    }
}
